import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  index,
  inet,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();

export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Stored lowercased; the unique index is on the normalized form.
    email: text("email").notNull(),
    emailVerified: boolean("email_verified").notNull().default(false),
    name: text("name").notNull(),
    // Null for passkey-only accounts.
    passwordHash: text("password_hash"),
    // WebAuthn user handle: random, opaque, and separate from `id` so
    // authenticators never hold the internal user ID.
    webauthnUserId: text("webauthn_user_id"),
    // Grants the admin panel (perks). Set from the command line, never the UI.
    isAdmin: boolean("is_admin").notNull().default(false),
    createdAt: createdAt(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("users_email_key").on(t.email), uniqueIndex("users_webauthn_user_id_key").on(t.webauthnUserId)],
);

/** A WebAuthn credential (passkey). Only public material is stored. */
export const passkeys = pgTable(
  "passkeys",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    // base64url credential ID, as the browser reports it.
    credentialId: text("credential_id").notNull(),
    // base64url COSE public key.
    publicKey: text("public_key").notNull(),
    signCount: bigint("sign_count", { mode: "number" }).notNull().default(0),
    transports: text("transports").array().notNull().default(sql`'{}'::text[]`),
    // multiDevice = synced passkey (iCloud Keychain, Google Password Manager…).
    deviceType: text("device_type").notNull(),
    backedUp: boolean("backed_up").notNull(),
    aaguid: text("aaguid").notNull(),
    name: text("name").notNull(),
    createdAt: createdAt(),
    lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("passkeys_credential_id_key").on(t.credentialId), index("passkeys_user_id_idx").on(t.userId)],
);

export const clientType = pgEnum("client_type", ["confidential", "public"]);
export const tokenEndpointAuthMethod = pgEnum("token_endpoint_auth_method", [
  "client_secret_basic",
  "client_secret_post",
  "none",
]);
export const subjectType = pgEnum("subject_type", ["public", "pairwise"]);
export const signingAlg = pgEnum("signing_alg", ["RS256", "ES256"]);

export const clients = pgTable("clients", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  logoUri: text("logo_uri"),
  type: clientType("type").notNull(),
  // SHA-256 of a 256-bit random secret. Secrets are generated by us, never
  // chosen by humans, so a slow password hash buys nothing here (see README).
  secretHash: text("secret_hash"),
  tokenEndpointAuthMethod: tokenEndpointAuthMethod("token_endpoint_auth_method").notNull(),
  redirectUris: text("redirect_uris").array().notNull(),
  postLogoutRedirectUris: text("post_logout_redirect_uris").array().notNull().default(sql`'{}'::text[]`),
  allowedScopes: text("allowed_scopes").array().notNull(),
  subjectType: subjectType("subject_type").notNull().default("pairwise"),
  // Pairwise subjects are derived from this. It's the redirect host, so two
  // clients on one host see the same `sub`; first-party Kingdom apps all
  // share one sector so they recognize the same person across apps.
  sectorIdentifier: text("sector_identifier").notNull(),
  firstParty: boolean("first_party").notNull().default(false),
  // PKCE is required unless explicitly waived at registration. The only
  // waiver in use is for the OpenID conformance suite's static clients,
  // whose Basic OP tests don't send PKCE (see conformance/README.md).
  requirePkce: boolean("require_pkce").notNull().default(true),
  idTokenSignedResponseAlg: signingAlg("id_token_signed_response_alg").notNull().default("RS256"),
  createdAt: createdAt(),
});

export const keyStatus = pgEnum("key_status", ["next", "active", "retiring", "retired"]);

export const signingKeys = pgTable(
  "signing_keys",
  {
    kid: text("kid").primaryKey(),
    alg: signingAlg("alg").notNull(),
    status: keyStatus("status").notNull(),
    publicJwk: jsonb("public_jwk").notNull(),
    // AES-256-GCM ciphertext of the private JWK: base64url(iv || tag || ct).
    privateJwkEncrypted: text("private_jwk_encrypted").notNull(),
    createdAt: createdAt(),
    activatedAt: timestamp("activated_at", { withTimezone: true }),
    retiringAt: timestamp("retiring_at", { withTimezone: true }),
    retiredAt: timestamp("retired_at", { withTimezone: true }),
  },
  (t) => [
    // At most one active key per algorithm, enforced by the database rather
    // than by the rotation code being careful.
    uniqueIndex("signing_keys_one_active_per_alg").on(t.alg).where(sql`${t.status} = 'active'`),
    uniqueIndex("signing_keys_one_next_per_alg").on(t.alg).where(sql`${t.status} = 'next'`),
  ],
);

export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // SHA-256 of the cookie value; a database read never yields a usable cookie.
    tokenHash: text("token_hash").notNull(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    authTime: timestamp("auth_time", { withTimezone: true }).notNull(),
    amr: text("amr").array().notNull(),
    ip: inet("ip"),
    userAgent: text("user_agent"),
    createdAt: createdAt(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true }).notNull().defaultNow(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("sessions_token_hash_key").on(t.tokenHash), index("sessions_user_id_idx").on(t.userId)],
);

export const consents = pgTable(
  "consents",
  {
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    clientId: text("client_id")
      .notNull()
      .references(() => clients.id, { onDelete: "cascade" }),
    scopes: text("scopes").array().notNull(),
    // The `sub` this client sees for this user. Stored rather than recomputed
    // so the userinfo endpoint can resolve a pairwise `sub` back to a user.
    subject: text("subject").notNull(),
    createdAt: createdAt(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    // Last token issued to this app for this user (code exchange or refresh).
    lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
  },
  (t) => [
    primaryKey({ columns: [t.userId, t.clientId] }),
    uniqueIndex("consents_client_subject_key").on(t.clientId, t.subject),
  ],
);

/**
 * One authorization: what a user granted a client through one code
 * exchange. Every access and refresh token minted from it carries its ID, so
 * revoking the grant (reuse detection, revocation, logout, disconnect) kills
 * all of them at once. A refresh token family is the grant's refresh tokens.
 */
export const grants = pgTable(
  "grants",
  {
    // Random, opaque: it appears in access tokens as `gid`.
    id: text("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    clientId: text("client_id")
      .notNull()
      .references(() => clients.id, { onDelete: "cascade" }),
    sessionId: uuid("session_id").references(() => sessions.id, { onDelete: "set null" }),
    subject: text("subject").notNull(),
    scopes: text("scopes").array().notNull(),
    authTime: timestamp("auth_time", { withTimezone: true }).notNull(),
    amr: text("amr").array().notNull(),
    // Hash of the authorization code it came from, so a replayed code can
    // find and revoke what the first redemption produced.
    codeHash: text("code_hash").notNull(),
    // Offline grants (offline_access) outlive the browser session; online
    // ones end with it.
    offline: boolean("offline").notNull(),
    createdAt: createdAt(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    revokedReason: text("revoked_reason"),
  },
  (t) => [
    uniqueIndex("grants_code_hash_key").on(t.codeHash),
    index("grants_user_client_idx").on(t.userId, t.clientId),
    index("grants_session_idx").on(t.sessionId),
  ],
);

export const refreshTokens = pgTable(
  "refresh_tokens",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    grantId: text("grant_id")
      .notNull()
      .references(() => grants.id, { onDelete: "cascade" }),
    tokenHash: text("token_hash").notNull(),
    createdAt: createdAt(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    // Set when this token is exchanged. Presenting it again is reuse.
    usedAt: timestamp("used_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("refresh_tokens_token_hash_key").on(t.tokenHash), index("refresh_tokens_grant_idx").on(t.grantId)],
);

export const perkRule = pgEnum("perk_rule", ["connected", "connected_days", "connected_apps", "manual"]);

/**
 * A perk an app offers. Once unlocked, a perk follows the user to every
 * first-party Kingdom app through the `perks` claim.
 *
 * Rules: `connected` (the user connected the offering app), `connected_days`
 * (connected for at least `threshold` days), `connected_apps` (connected at
 * least `threshold` Kingdom apps), `manual` (granted by an admin).
 */
export const perks = pgTable(
  "perks",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Stable identifier apps key on, e.g. "cappuccino.early-supporter".
    slug: text("slug").notNull(),
    clientId: text("client_id")
      .notNull()
      .references(() => clients.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    description: text("description").notNull(),
    rule: perkRule("rule").notNull(),
    threshold: bigint("threshold", { mode: "number" }),
    active: boolean("active").notNull().default(true),
    createdAt: createdAt(),
  },
  (t) => [uniqueIndex("perks_slug_key").on(t.slug), index("perks_client_idx").on(t.clientId)],
);

/** Perks granted by hand (rule `manual`). */
export const perkGrants = pgTable(
  "perk_grants",
  {
    perkId: uuid("perk_id")
      .notNull()
      .references(() => perks.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    createdAt: createdAt(),
  },
  (t) => [primaryKey({ columns: [t.perkId, t.userId] })],
);

/**
 * Security-relevant account activity, shown in Watchtower. Written directly
 * for now; phase 7 moves the write path onto a Redis Stream with detection
 * rules in front of this table.
 */
export const securityEvents = pgTable(
  "security_events",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Null when the event can't be tied to an account.
    userId: uuid("user_id").references(() => users.id, { onDelete: "cascade" }),
    type: text("type").notNull(),
    clientId: text("client_id"),
    ip: inet("ip"),
    userAgent: text("user_agent"),
    details: jsonb("details").notNull().default(sql`'{}'::jsonb`),
    createdAt: createdAt(),
  },
  (t) => [index("security_events_user_time_idx").on(t.userId, t.createdAt)],
);

export type User = typeof users.$inferSelect;
export type Client = typeof clients.$inferSelect;
export type NewClient = typeof clients.$inferInsert;
export type SigningKey = typeof signingKeys.$inferSelect;
export type Session = typeof sessions.$inferSelect;
export type Consent = typeof consents.$inferSelect;
export type Grant = typeof grants.$inferSelect;
export type Passkey = typeof passkeys.$inferSelect;
export type Perk = typeof perks.$inferSelect;
export type SecurityEvent = typeof securityEvents.$inferSelect;
export type RefreshToken = typeof refreshTokens.$inferSelect;
